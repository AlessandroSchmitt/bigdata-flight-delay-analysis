#!/usr/bin/env python3
"""Generate report-ready local benchmark charts from local_summary.csv."""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

import matplotlib.pyplot as plt


TECH_LABELS = {
    "spark_sql": "Spark SQL",
    "spark_core": "Spark Core",
    "hive": "Hive / Tez",
}

TECH_ORDER = ("spark_sql", "spark_core", "hive")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--input",
        default="benchmark-results/local_summary.csv",
        help="Summary CSV generated by summarize_local_benchmarks.py",
    )
    parser.add_argument(
        "--output-dir",
        default="benchmark-results/figures",
        help="Directory for generated figures",
    )
    return parser.parse_args()


def read_summary(path: Path):
    rows = []
    with path.open(newline="", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            rows.append(
                {
                    "job": int(row["job"]),
                    "technology": row["technology"],
                    "input_rows": int(row["input_rows"]),
                    "median_seconds": float(row["median_seconds"]),
                    "stdev_seconds": float(row["stdev_seconds"]),
                }
            )
    return rows


def plot_job(rows, job: int, output_dir: Path) -> None:
    job_rows = [row for row in rows if row["job"] == job]
    if not job_rows:
        raise ValueError(f"No benchmark rows found for Job {job}")

    by_tech = defaultdict(list)
    for row in job_rows:
        by_tech[row["technology"]].append(row)

    fig, ax = plt.subplots(figsize=(8.0, 5.0))

    for tech in TECH_ORDER:
        values = sorted(by_tech[tech], key=lambda row: row["input_rows"])
        x = [row["input_rows"] / 1_000_000 for row in values]
        y = [row["median_seconds"] for row in values]
        err = [row["stdev_seconds"] for row in values]

        ax.errorbar(
            x,
            y,
            yerr=err,
            marker="o",
            capsize=4,
            label=TECH_LABELS[tech],
        )

    ax.set_xlabel("Input size (million records)")
    ax.set_ylabel("Wall-clock time (s)")
    ax.set_title(f"Local execution time — Job {job}")
    ax.grid(True, alpha=0.25)
    ax.legend()
    fig.tight_layout()

    png = output_dir / f"local_job{job}_execution_time.png"
    pdf = output_dir / f"local_job{job}_execution_time.pdf"
    fig.savefig(png, dpi=200, bbox_inches="tight")
    fig.savefig(pdf, bbox_inches="tight")
    plt.close(fig)

    print(f"[OK] {png}")
    print(f"[OK] {pdf}")


def main() -> None:
    args = parse_args()
    input_path = Path(args.input)
    output_dir = Path(args.output_dir)

    if not input_path.is_file():
        raise SystemExit(f"[ERROR] Missing benchmark summary: {input_path}")

    output_dir.mkdir(parents=True, exist_ok=True)
    rows = read_summary(input_path)

    plot_job(rows, 1, output_dir)
    plot_job(rows, 2, output_dir)


if __name__ == "__main__":
    main()
